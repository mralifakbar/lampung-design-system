const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, 'n$1');
function dartColor(v) {
  const hex = v.match(/^#([0-9a-f]{6})$/i);
  if (hex) return `Color(0xFF${hex[1].toUpperCase()})`;
  const m = v.match(/^rgba?\(\s*(\d+),\s*(\d+),\s*(\d+)(?:,\s*([\d.]+))?\s*\)$/i);
  if (!m) throw new Error('Unsupported color for Dart: ' + v);
  const a = Math.round((m[4] == null ? 1 : Number(m[4])) * 255);
  const h = (n) => Number(n).toString(16).padStart(2, '0').toUpperCase();
  return `Color(0x${h(a)}${h(m[1])}${h(m[2])}${h(m[3])})`;
}
