// Tailwind v3 shadcn expects bare "H S% L%" channels. Translucent roles are composited over
// that mode's canvas, which is where shadcn draws them.
function hslChannels(v, canvas) {
  const rgb = (s) => {
    const hex = s.match(/^#([0-9a-f]{6})$/i);
    if (hex) return [0, 2, 4].map((i) => parseInt(hex[1].slice(i, i + 2), 16)).concat(1);
    const m = s.match(/^rgba?\(\s*(\d+),\s*(\d+),\s*(\d+)(?:,\s*([\d.]+))?\s*\)$/i);
    return [+m[1], +m[2], +m[3], m[4] == null ? 1 : +m[4]];
  };
  const [r0, g0, b0, a] = rgb(v);
  const [cr, cg, cb] = rgb(canvas);
  const [r, g, b] = [[r0, cr], [g0, cg], [b0, cb]].map(([c, bg]) => (c * a + bg * (1 - a)) / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  let h = 0, s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h *= 60;
  }
  const f = (n) => +n.toFixed(1);
  return `${f(h)} ${f(s * 100)}% ${f(l * 100)}%`;
}
const v3Vars = (mode) => ({
  ...Object.fromEntries(Object.entries(SHADCN_COLORS).map(([k, role]) => [k, hslChannels(t.color[mode][role], t.color[mode]['bg-canvas'])])),
  ...Object.fromEntries(ELEVATIONS.map((k) => [`elevation-${k.slice(7)}`, t.shadow[mode][k]]))
});

