// Builds the aksara Lampung outputs from aksara/glyphs.json:
//   js/aksara-glyphs.js        glyph data imported by js/aksara.js (browser, no JSON import needed)
//   aksara/glyphs/<name>.svg   one file per letter and sign, for design tools
//   aksara/lds-aksara.svg      a sprite: <use href="lds-aksara.svg#ka"/>
//   dist/flutter/aksara_glyphs.dart and packages/flutter/lib/src/aksara_glyphs.g.dart (when the package exists)
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(root, 'aksara/glyphs.json'), 'utf8'));
const write = (p, s) => { mkdirSync(dirname(join(root, p)), { recursive: true }); writeFileSync(join(root, p), s); console.log(`wrote ${p}`); };

const { stroke, letters } = src;
const marks = { above: src.marks.above, below: src.marks.below, after: src.marks.after };
for (const group of Object.values(marks)) delete group.$description;

for (const [name, d] of Object.entries(letters)) {
  if (!Array.isArray(d) || !d.length) throw new Error(`aksara: letter "${name}" has no strokes`);
  for (const p of d) if (!/^M[\d\s.LQCZ-]+$/.test(p)) throw new Error(`aksara: letter "${name}" has an unexpected path command: ${p}`);
}

const header = '// Generated by scripts/build-aksara.mjs from aksara/glyphs.json. Do not edit.\n';
write('js/aksara-glyphs.js', `${header}export const GLYPHS = ${JSON.stringify({ stroke, letters, marks }, null, 2)};\n`);

const svgFile = (paths, viewBox) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">${paths.map((d) => `<path d="${d}"/>`).join('')}</svg>\n`;
const glyphDir = join(root, 'aksara/glyphs');
if (existsSync(glyphDir)) rmSync(glyphDir, { recursive: true });
const symbols = [];
for (const [name, d] of Object.entries(letters)) {
  write(`aksara/glyphs/${name}.svg`, svgFile(d, '0 -16 100 128'));
  symbols.push(`<symbol id="${name}" viewBox="0 -16 100 128">${d.map((p) => `<path d="${p}"/>`).join('')}</symbol>`);
}
for (const [pos, group] of Object.entries(marks)) for (const [name, d] of Object.entries(group)) {
  const id = `${pos}-${name.normalize('NFD').replace(/[̀-ͯ]/g, '') === name ? name : 'e-acute'}`;
  write(`aksara/glyphs/${id}.svg`, svgFile(d, pos === 'after' ? '0 -16 28 128' : '0 -16 100 128'));
  symbols.push(`<symbol id="${id}" viewBox="${pos === 'after' ? '0 -16 28 128' : '0 -16 100 128'}">${d.map((p) => `<path d="${p}"/>`).join('')}</symbol>`);
}
write('aksara/lds-aksara.svg', `<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">\n${symbols.join('\n')}\n</svg>\n`);

// Flutter: the same paths as Dart constants, drawn by a CustomPainter in the package.
const dartList = (arr) => `[${arr.map((p) => `'${p}'`).join(', ')}]`;
const dartMap = (obj) => `{\n${Object.entries(obj).map(([k, v]) => `    '${k}': ${dartList(v)},`).join('\n')}\n  }`;
const dart = `// Generated by scripts/build-aksara.mjs from aksara/glyphs.json. Do not edit.
// ignore_for_file: public_member_api_docs

/// Stroke paths of the aksara Lampung glyphs on a 100 x 100 grid (y from -16 to 112).
abstract final class LdsAksaraGlyphs {
  static const double stroke = ${stroke};
  static const Map<String, List<String>> letters = ${dartMap(letters)};
  static const Map<String, List<String>> above = ${dartMap(marks.above)};
  static const Map<String, List<String>> below = ${dartMap(marks.below)};
  static const Map<String, List<String>> after = ${dartMap(marks.after)};
}
`;
write('dist/flutter/aksara_glyphs.dart', dart);
if (existsSync(join(root, 'packages/flutter/lib/src'))) write('packages/flutter/lib/src/aksara_glyphs.g.dart', dart);
