const bezier = (a) => `cubic-bezier(${a.join(', ')})`;
const springCss = (s) => `linear(${s.points.join(', ')})`;
const em = (n) => (n === 0 ? '0' : `${n}em`);

// ---------- CSS ----------
function themeBlock(mode) {
  const lines = [];
  for (const [k, v] of Object.entries(t.color[mode])) lines.push(`  --${k}: ${v};`);
  for (const [k, v] of Object.entries(t.shadow[mode])) lines.push(`  --${k}: ${v};`);
  for (const [k, v] of Object.entries(t.filter?.[mode] || {})) lines.push(`  --${k}: ${v};`);
  return lines.join('\n');
}
function staticBlock() {
  const l = [];
  l.push(`  --font: ${t.font.sans};`, `  --mono: ${t.font.mono};`, `  --font-icons: ${t.font.icons};`, `  --font-icons-fill: ${t.font['icons-fill']};`);
  for (const [k, s] of Object.entries(t.type)) {
    l.push(`  --type-${k}: ${s.weight} ${s.size}px/${s.line}px var(--font);`);
    l.push(`  --tracking-${k}: ${em(s.tracking)};`);
  }
  for (const [k, v] of Object.entries(t.space)) l.push(`  --s-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(t.radius)) l.push(`  --r-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(t.size)) l.push(`  --size-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(t.motion.duration)) l.push(`  --d-${k}: ${v}ms;`);
  l.push(`  --d-momentum: ${t.motion.spring.momentum.duration}ms;`);
  for (const [k, v] of Object.entries(t.motion.easing)) l.push(`  --ease-${k}: ${bezier(v)};`);
  for (const [k, s] of Object.entries(t.motion.spring)) l.push(`  --spring-${k}: ${springCss(s)};`);
  return l.join('\n');
}
// Accent presets (data-accent="<name>"): only the accent roles change, for the light and dark themes,
// including when data-accent and data-theme sit on different elements. When both sit on the same element
// the selector repeats [data-theme] so it outranks a theme set on an ancestor.
function accentBlocks() {
  const out = [];
  for (const [name, a] of Object.entries(t.accents || {})) {
    if (name.startsWith('$')) continue;
    const vars = (mode) => Object.entries(a[mode]).map(([k, v]) => `  --${k}: ${v};`).join('\n');
    const sel = `[data-accent="${name}"]`;
    out.push(`/* ${a.label}: ${a.story} */
${sel},
${sel} [data-theme="light"],
[data-theme="light"][data-theme]${sel},
[data-theme="light"] ${sel} {
${vars('light')}
}
[data-theme="dark"][data-theme]${sel},
[data-theme="dark"] ${sel},
${sel} [data-theme="dark"] {
${vars('dark')}
}
@media (prefers-color-scheme: dark) {
  [data-theme="system"][data-theme]${sel},
  [data-theme="system"] ${sel},
  ${sel} [data-theme="system"] {
${vars('dark').replace(/^/gm, '  ')}
  }
}`);
  }
  return out.join('\n\n');
}
