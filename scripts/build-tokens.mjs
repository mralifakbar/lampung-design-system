// Single-word and nested names: "primary-foreground" -> colors.primary.foreground.
const v3Colors = {};
const GROUPS = ['card', 'popover', 'primary', 'secondary', 'muted', 'accent', 'destructive', 'chart', 'sidebar', 'success', 'warning', 'inverse'];
for (const k of Object.keys(SHADCN_COLORS)) {
  const value = `hsl(var(--${k}) / <alpha-value>)`;
  const group = GROUPS.find((g) => k === g || k.startsWith(g + '-'));
  if (!group) v3Colors[k] = value;
  else {
    const sub = k === group ? 'DEFAULT' : k.slice(group.length + 1);
    (v3Colors[group] ??= {})[sub] = value;
  }
}
const fontList = (css) => css.split(',').map((f) => f.trim());
const indentJson = (o) => JSON.stringify(o, null, 2).replace(/\n/g, '\n      ');
write('dist/shadcn/tailwind.preset.cjs', `// ${HEADER}
// Tailwind CSS v3 preset for shadcn/ui: presets: [require('lampung-design-system/shadcn/tailwind-preset')]
module.exports = {
  darkMode: ['variant', ['&:is(.dark *)', '&:is([data-theme="dark"] *)']],
  theme: {
    extend: {
      colors: ${indentJson(v3Colors)},
      borderRadius: {
        sm: 'calc(var(--radius) - 4px)',
        md: 'calc(var(--radius) - 2px)',
        lg: 'var(--radius)',
        xl: 'calc(var(--radius) + 4px)',
        '2xl': '${t.radius.xl}px'
      },
      boxShadow: ${indentJson(Object.fromEntries(Object.entries(SHADCN_SHADOW).map(([k, v]) => [k, `var(--elevation-${v.slice(7)})`])))},
      fontFamily: {
        sans: ${JSON.stringify(fontList(t.font.sans))},
        mono: ${JSON.stringify(fontList(t.font.mono))}
      },
      fontSize: ${indentJson(Object.fromEntries(Object.entries(t.type).map(([k, s]) => [k, [`${s.size}px`, { lineHeight: `${s.line}px`, letterSpacing: em(s.tracking), fontWeight: `${s.weight}` }]])))},
      letterSpacing: ${indentJson({ tighter: shadcnThemeShared['tracking-tighter'], tight: shadcnThemeShared['tracking-tight'], normal: bodyTracking, wide: shadcnThemeShared['tracking-wide'] })},
      transitionTimingFunction: ${indentJson(Object.fromEntries(Object.entries(shadcnEase).map(([k, v]) => [k.slice(5), v])))}
    }
  }
};
`);
